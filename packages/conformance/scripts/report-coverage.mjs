/**
 * Generates COVERAGE.md from coverage.json + rule-inventory.json.
 * Run after changing coverage; the file is checked in as documentation.
 */
import { readFileSync, writeFileSync } from "node:fs";

const coverage = JSON.parse(readFileSync(new URL("../coverage.json", import.meta.url), "utf8"));
const inventory = JSON.parse(readFileSync(new URL("../rule-inventory.json", import.meta.url), "utf8"));

const byRuleset = new Map(inventory.rules.map((rule) => [rule.id, rule.ruleset]));
const entries = Object.entries(coverage.rules);
const totals = {};
for (const [, entry] of entries) totals[entry.status] = (totals[entry.status] ?? 0) + 1;

const fixtureCount = new Set(entries.flatMap(([, entry]) => entry.fixtures)).size;

const lines = [
  `# PINT A-NZ ${coverage.rulesetVersion} rule coverage`,
  "",
  "Generated by `pnpm --filter @pint-anz/conformance report`. Do not edit by hand.",
  "",
  `Ruleset version: **${coverage.rulesetVersion}** — ${inventory.counts.total} rules ` +
    `(${inventory.counts.pint} shared PINT + ${inventory.counts.aligned} A-NZ aligned).`,
  "",
  "## Totals",
  "",
  "| Status | Rules |",
  "|---|---|",
  ...Object.keys(coverage.statuses)
    .filter((status) => totals[status])
    .map((status) => `| ${status} | ${totals[status]} |`),
  `| **total** | **${entries.length}** |`,
  "",
  `Distinct fixtures referenced: ${fixtureCount}.`,
  "",
  "## Status definitions",
  "",
  ...Object.entries(coverage.statuses).map(([status, definition]) => `- **${status}** — ${definition}`),
  "",
];

const exceptions = entries.filter(([, entry]) =>
  ["valid-covered", "not-applicable", "blocked"].includes(entry.status),
);
if (exceptions.length > 0) {
  lines.push("## Known exceptions (no isolated negative fixture)", "");
  lines.push("| Rule | Ruleset | Status | Independent observation |", "|---|---|---|---|");
  for (const [id, entry] of exceptions.sort(([a], [b]) => a.localeCompare(b))) {
    lines.push(`| ${id} | ${byRuleset.get(id)} | ${entry.status} | ${entry.observation.replaceAll("|", "\\|")} |`);
  }
  lines.push("");
}

const unreviewed = entries.filter(([, entry]) => entry.status === "unreviewed");
if (unreviewed.length > 0) {
  lines.push("## Unreviewed rules", "");
  lines.push(unreviewed.map(([id]) => `\`${id}\``).join(", "), "");
}

writeFileSync(new URL("../COVERAGE.md", import.meta.url), `${lines.join("\n")}\n`);
console.log(
  `COVERAGE.md: ${Object.entries(totals)
    .map(([status, count]) => `${count} ${status}`)
    .join(", ")}`,
);
